CCodeGenerator::CCodeGenerator(const Program& program, bool aerospace_profile)
    : program_(program), aerospace_profile_(aerospace_profile) {}

void CCodeGenerator::indent() {
    for (int i = 0; i < indent_level_; ++i) {
        out_ << "    ";
    }
}

void CCodeGenerator::line(const std::string& str) {
    if (!str.empty()) {
        indent();
        out_ << str;
    }
    out_ << "\n";
}

std::string CCodeGenerator::map_type(const Type& type) {
    std::string base;
    switch (type.kind) {
        case BaseTypeKind::Unit: base = "void"; break;
        case BaseTypeKind::I32: base = "int32_t"; break;
        case BaseTypeKind::Bool: base = "bool"; break;
        case BaseTypeKind::Str: return "const char*";
        case BaseTypeKind::Array:
        case BaseTypeKind::Slice: {
            std::string elem = type.type_args.empty() ? "int32_t" : map_type(type.type_args[0]);
            if (type.is_ref) {
                return (type.is_mut_ref ? (elem + "*") : ("const " + elem + "*"));
            }
            return elem + "*";
        }
        case BaseTypeKind::Named: base = type.name; break;
        case BaseTypeKind::GenericParam: base = type.name; break;
        case BaseTypeKind::PhysicalUnit: base = "int32_t"; break;
        case BaseTypeKind::F32: base = "float"; break;
        case BaseTypeKind::F64: base = "double"; break;
    }
    if (type.is_ref) {
        if (type.is_mut_ref) {
            return base + "*";
        } else {
            return "const " + base + "*";
        }
    }
    return base;
}

std::string CCodeGenerator::generate() {
    out_.str("");
    out_.clear();

    emit_includes();
    if (aerospace_profile_) {
        emit_aerospace_traps();
    }
    emit_struct_declarations();
    emit_enum_declarations();
    emit_state_machine_declarations();
    emit_enum_constructors();
    emit_state_machine_methods();
    emit_forward_declarations();

    for (const auto& fn : program_.functions) {
        emit_function(*fn);
    }
    for (const auto& ib : program_.impl_blocks) {
        for (const auto& fn : ib->methods) {
            emit_function(*fn);
        }
    }

    return out_.str();
}

