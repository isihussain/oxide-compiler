void CCodeGenerator::emit_struct_declarations() {
    for (const auto& s : program_.structs) {
        line("typedef struct {");
        indent_level_++;
        for (const auto& f : s->fields) {
            line(map_type(f.type) + " " + f.name + ";");
        }
        indent_level_--;
        line("} " + s->name + ";");
        line();
    }
}

void CCodeGenerator::emit_enum_declarations() {
    for (const auto& e : program_.enums) {
        // Tag enum
        line("typedef enum {");
        indent_level_++;
        for (const auto& v : e->variants) {
            line(e->name + "_Tag_" + v.name + " = " + std::to_string(v.tag) + ",");
        }
        indent_level_--;
        line("} " + e->name + "_Tag;");
        line();

        // Tagged union struct
        line("typedef struct {");
        indent_level_++;
        line("int tag;");
        bool has_payload = false;
        for (const auto& v : e->variants) {
            if (v.payload_type.has_value()) {
                has_payload = true;
                break;
            }
        }
        if (has_payload) {
            line("union {");
            indent_level_++;
            for (const auto& v : e->variants) {
                if (v.payload_type.has_value()) {
                    line(map_type(*v.payload_type) + " " + v.name + ";");
                }
            }
            indent_level_--;
            line("} data;");
        }
        indent_level_--;
        line("} " + e->name + ";");
        line();
    }
}

void CCodeGenerator::emit_state_machine_declarations() {
    for (const auto& sm : program_.state_machines) {
        // Tag enum
        line("typedef enum {");
        indent_level_++;
        int tag = 0;
        for (const auto& s : sm->states) {
            line(sm->name + "_Tag_" + s + " = " + std::to_string(tag++) + ",");
        }
        for (const auto& s : sm->terminal_states) {
            line(sm->name + "_Tag_" + s + " = " + std::to_string(tag++) + ",");
        }
        indent_level_--;
        line("} " + sm->name + "_Tag;");
        line();

        // Tagged struct
        line("typedef struct {");
        indent_level_++;
        line("int tag;");
        indent_level_--;
        line("} " + sm->name + ";");
        line();
    }
}

void CCodeGenerator::emit_enum_constructors() {
    for (const auto& e : program_.enums) {
        for (const auto& v : e->variants) {
            if (v.payload_type.has_value()) {
                line("static inline " + e->name + " " + e->name + "_" + v.name + "(" + map_type(*v.payload_type) + " val) {");
                indent_level_++;
                line(e->name + " _res;");
                line("_res.tag = " + e->name + "_Tag_" + v.name + ";");
                line("_res.data." + v.name + " = val;");
                line("return _res;");
                indent_level_--;
                line("}");
                line();
            } else {
                line("static inline " + e->name + " " + e->name + "_" + v.name + "(void) {");
                indent_level_++;
                line(e->name + " _res;");
                line("_res.tag = " + e->name + "_Tag_" + v.name + ";");
                line("return _res;");
                indent_level_--;
                line("}");
                line();
            }
        }
    }
}

void CCodeGenerator::emit_state_machine_methods() {
    for (const auto& sm : program_.state_machines) {
        // Constructors
        for (const auto& s : sm->states) {
            line("static inline " + sm->name + " " + sm->name + "_" + s + "(void) {");
            indent_level_++;
            line(sm->name + " _res;");
            line("_res.tag = " + sm->name + "_Tag_" + s + ";");
            line("return _res;");
            indent_level_--;
            line("}");
            line();
        }
        for (const auto& s : sm->terminal_states) {
            line("static inline " + sm->name + " " + sm->name + "_" + s + "(void) {");
            indent_level_++;
            line(sm->name + " _res;");
            line("_res.tag = " + sm->name + "_Tag_" + s + ";");
            line("return _res;");
            indent_level_--;
            line("}");
            line();
        }

        // can_transition
        line("static inline bool " + sm->name + "__can_transition(" + sm->name + " from, " + sm->name + " to) {");
        indent_level_++;
        line("switch (from.tag) {");
        indent_level_++;
        std::map<std::string, std::vector<std::string>> trans_map;
        for (const auto& t : sm->transitions) {
            trans_map[t.from_state].push_back(t.to_state);
        }
        for (const auto& [from_st, to_list] : trans_map) {
            line("case " + sm->name + "_Tag_" + from_st + ":");
            indent_level_++;
            std::string cond = "";
            for (size_t i = 0; i < to_list.size(); ++i) {
                if (i > 0) cond += " || ";
                cond += "to.tag == " + sm->name + "_Tag_" + to_list[i];
            }
            line("if (" + cond + ") return true;");
            line("return false;");
            indent_level_--;
        }
        line("default:");
        indent_level_++;
        line("return false;");
        indent_level_--;
        indent_level_--;
        line("}");
        indent_level_--;
        line("}");
        line();

        // transition
        line("static inline " + sm->name + " " + sm->name + "__transition(" + sm->name + " from, " + sm->name + " to) {");
        indent_level_++;
        line("if (!" + sm->name + "__can_transition(from, to)) {");
        indent_level_++;
        line("fprintf(stderr, \"[OXIDE STATE MACHINE] Illegal transition in " + sm->name + " from tag %d to tag %d\\n\", from.tag, to.tag);");
        line("abort();");
        indent_level_--;
        line("}");
        line("return to;");
        indent_level_--;
        line("}");
        line();
    }
}

void CCodeGenerator::emit_forward_declarations() {
    for (const auto& eb : program_.extern_blocks) {
        for (const auto& decl : eb->declarations) {
            out_ << "extern " << map_type(decl.return_type) << " " << decl.name << "(";
            if (decl.parameters.empty()) {
                out_ << "void";
            } else {
                for (size_t i = 0; i < decl.parameters.size(); ++i) {
                    if (i > 0) out_ << ", ";
                    out_ << map_type(decl.parameters[i].type) << " " << decl.parameters[i].name;
                }
            }
            out_ << ");\n";
        }
    }

    for (const auto& fn : program_.functions) {
        out_ << map_type(fn->return_type) << " " << fn->name << "(";
        if (fn->parameters.empty()) {
            out_ << "void";
        } else {
            for (size_t i = 0; i < fn->parameters.size(); ++i) {
                if (i > 0) out_ << ", ";
                out_ << map_type(fn->parameters[i].type) << " " << fn->parameters[i].name;
            }
        }
        out_ << ");\n";
    }

    for (const auto& ib : program_.impl_blocks) {
        for (const auto& fn : ib->methods) {
            out_ << map_type(fn->return_type) << " " << fn->name << "(";
            if (fn->parameters.empty()) {
                out_ << "void";
            } else {
                for (size_t i = 0; i < fn->parameters.size(); ++i) {
                    if (i > 0) out_ << ", ";
                    out_ << map_type(fn->parameters[i].type) << " " << fn->parameters[i].name;
                }
            }
            out_ << ");\n";
        }
    }
    line();
}

void CCodeGenerator::emit_function(const Function& fn) {
    if (fn.has_attribute("tmr")) {
        // Emit triplicated implementation function
        indent();
        out_ << "static " << map_type(fn.return_type) << " " << fn.name << "__tmr_channel(";
        if (fn.parameters.empty()) {
            out_ << "void";
        } else {
            for (size_t i = 0; i < fn.parameters.size(); ++i) {
                if (i > 0) out_ << ", ";
                out_ << map_type(fn.parameters[i].type) << " " << fn.parameters[i].name;
            }
        }
        out_ << ") ";
        emit_block(*fn.body, true, false);
        line();

        // Emit public wrapper executing 3 channels and voting
        indent();
        out_ << map_type(fn.return_type) << " " << fn.name << "(";
        if (fn.parameters.empty()) {
            out_ << "void";
        } else {
            for (size_t i = 0; i < fn.parameters.size(); ++i) {
                if (i > 0) out_ << ", ";
                out_ << map_type(fn.parameters[i].type) << " " << fn.parameters[i].name;
            }
        }
        out_ << ") {\n";
        indent_level_++;
        std::string args_str;
        for (size_t i = 0; i < fn.parameters.size(); ++i) {
            if (i > 0) args_str += ", ";
            args_str += fn.parameters[i].name;
        }
        if (fn.return_type.kind == BaseTypeKind::Unit) {
            line(fn.name + "__tmr_channel(" + args_str + ");");
            line(fn.name + "__tmr_channel(" + args_str + ");");
            line(fn.name + "__tmr_channel(" + args_str + ");");
        } else {
            std::string t_str = map_type(fn.return_type);
            line(t_str + " _ch0 = " + fn.name + "__tmr_channel(" + args_str + ");");
            line(t_str + " _ch1 = " + fn.name + "__tmr_channel(" + args_str + ");");
            line(t_str + " _ch2 = " + fn.name + "__tmr_channel(" + args_str + ");");
            const char* voter = "__oxide_tmr_vote_i32";
            if (fn.return_type.kind == BaseTypeKind::F32) {
                voter = "__oxide_tmr_vote_f32";
            } else if (fn.return_type.kind == BaseTypeKind::F64) {
                voter = "__oxide_tmr_vote_f64";
            } else if (fn.return_type.kind == BaseTypeKind::Bool) {
                voter = "__oxide_tmr_vote_bool";
            }
            line("return " + std::string(voter) + "(_ch0, _ch1, _ch2, \"" + fn.name + "\");");
        }
        indent_level_--;
        line("}");
        line();
        return;
    }

    indent();
    out_ << map_type(fn.return_type) << " " << fn.name << "(";
    if (fn.parameters.empty()) {
        out_ << "void";
    } else {
        for (size_t i = 0; i < fn.parameters.size(); ++i) {
            if (i > 0) out_ << ", ";
            out_ << map_type(fn.parameters[i].type) << " " << fn.parameters[i].name;
        }
    }
    out_ << ") ";
    emit_block(*fn.body, true, fn.name == "main");
    line();
}

void CCodeGenerator::emit_block(const BlockExpr& block, bool is_function_body, bool is_main) {
    out_ << "{\n";
    indent_level_++;

    if (is_main && aerospace_profile_) {
        line("__oxide_enable_aerospace_ftz();");
    }

    for (const auto& stmt : block.statements) {
        emit_statement(*stmt);
    }

    if (block.trailing_expr) {
        if (auto* if_expr = dynamic_cast<const IfExpr*>(block.trailing_expr.get())) {
            if (block.evaluated_type.kind == BaseTypeKind::Unit) {
                indent();
                if (dynamic_cast<const BinaryExpr*>(if_expr->condition.get())) {
                    out_ << "if ";
                    emit_expression(*if_expr->condition);
                    out_ << " ";
                } else {
                    out_ << "if (";
                    emit_expression(*if_expr->condition);
                    out_ << ") ";
                }
                emit_block(*if_expr->then_branch, false);
                if (if_expr->else_branch) {
                    indent();
                    out_ << "else ";
                    emit_block(*if_expr->else_branch, false);
                }
            } else {
                indent();
                if (is_function_body && block.evaluated_type.kind != BaseTypeKind::Unit) {
                    out_ << "return ";
                }
                emit_expression(*block.trailing_expr);
                out_ << ";\n";
            }
        } else {
            indent();
            if (is_function_body && block.evaluated_type.kind != BaseTypeKind::Unit) {
                out_ << "return ";
            }
            emit_expression(*block.trailing_expr);
            out_ << ";\n";
        }
    } else if (is_function_body && block.evaluated_type.kind != BaseTypeKind::Unit) {
        bool ends_with_return = false;
        if (!block.statements.empty()) {
            if (auto* es = dynamic_cast<const ExprStmt*>(block.statements.back().get())) {
                if (dynamic_cast<const ReturnExpr*>(es->expr.get())) {
                    ends_with_return = true;
                }
            }
        }
        if (!ends_with_return) {
            indent();
            out_ << "return 0;\n";
        }
    }

    indent_level_--;
    indent();
    out_ << "}\n";
}

void CCodeGenerator::emit_statement(const Statement& stmt) {
    if (auto* let = dynamic_cast<const LetStmt*>(&stmt)) {
        indent();
        if (let->declared_type.kind == BaseTypeKind::Array && !let->declared_type.is_ref) {
            std::string elem = map_type(let->declared_type.type_args.empty() ? Type{BaseTypeKind::I32} : let->declared_type.type_args[0]);
            out_ << elem << " " << let->var_name << "[" << let->declared_type.array_size << "]";
            if (let->initializer) {
                out_ << " = ";
                emit_expression(*let->initializer);
            }
            out_ << ";\n";
            return;
        }
        out_ << map_type(let->declared_type) << " " << let->var_name;
        if (let->initializer) {
            out_ << " = ";
            emit_expression(*let->initializer);
        }
        out_ << ";\n";
    } else if (auto* expr_stmt = dynamic_cast<const ExprStmt*>(&stmt)) {
        if (expr_stmt->expr) {
            if (auto* if_expr = dynamic_cast<const IfExpr*>(expr_stmt->expr.get())) {
                indent();
                if (dynamic_cast<const BinaryExpr*>(if_expr->condition.get())) {
                    out_ << "if ";
                    emit_expression(*if_expr->condition);
                    out_ << " ";
                } else {
                    out_ << "if (";
                    emit_expression(*if_expr->condition);
                    out_ << ") ";
                }
                emit_block(*if_expr->then_branch, false);
                if (if_expr->else_branch) {
                    indent();
                    out_ << "else ";
                    emit_block(*if_expr->else_branch, false);
                }
                return;
            }
            if (auto* for_expr = dynamic_cast<const ForExpr*>(expr_stmt->expr.get())) {
                indent();
                emit_expression(*for_expr);
                out_ << "\n";
                return;
            }
            indent();
            emit_expression(*expr_stmt->expr);
            out_ << ";\n";
        }
    }
}

void CCodeGenerator::emit_expression(const Expression& expr) {
    if (auto* int_lit = dynamic_cast<const IntegerLiteralExpr*>(&expr)) {
        out_ << int_lit->value;
    } else if (auto* fl_lit = dynamic_cast<const FloatLiteralExpr*>(&expr)) {
        std::ostringstream ss;
        ss << std::setprecision(12) << fl_lit->value;
        std::string s = ss.str();
        if (s.find('.') == std::string::npos && s.find('e') == std::string::npos && s.find('E') == std::string::npos) {
            s += ".0";
        }
        if (fl_lit->evaluated_type.kind == BaseTypeKind::F32) {
            s += "f";
        }
        out_ << s;
    } else if (auto* bool_lit = dynamic_cast<const BoolLiteralExpr*>(&expr)) {
        out_ << (bool_lit->value ? "true" : "false");
    } else if (auto* var = dynamic_cast<const VariableExpr*>(&expr)) {
        out_ << var->name;
    } else if (auto* bin = dynamic_cast<const BinaryExpr*>(&expr)) {
        if (aerospace_profile_ && (bin->op == BinaryOp::Add || bin->op == BinaryOp::Sub ||
                                   bin->op == BinaryOp::Mul || bin->op == BinaryOp::Div)) {
            const char* fn_name = "";
            if (bin->evaluated_type.kind == BaseTypeKind::F32) {
                switch (bin->op) {
                    case BinaryOp::Add: fn_name = "__oxide_checked_fadd_f32"; break;
                    case BinaryOp::Sub: fn_name = "__oxide_checked_fsub_f32"; break;
                    case BinaryOp::Mul: fn_name = "__oxide_checked_fmul_f32"; break;
                    case BinaryOp::Div: fn_name = "__oxide_checked_fdiv_f32"; break;
                    default: break;
                }
            } else if (bin->evaluated_type.kind == BaseTypeKind::F64) {
                switch (bin->op) {
                    case BinaryOp::Add: fn_name = "__oxide_checked_fadd_f64"; break;
                    case BinaryOp::Sub: fn_name = "__oxide_checked_fsub_f64"; break;
                    case BinaryOp::Mul: fn_name = "__oxide_checked_fmul_f64"; break;
                    case BinaryOp::Div: fn_name = "__oxide_checked_fdiv_f64"; break;
                    default: break;
                }
            } else {
                switch (bin->op) {
                    case BinaryOp::Add: fn_name = "__oxide_checked_add"; break;
                    case BinaryOp::Sub: fn_name = "__oxide_checked_sub"; break;
                    case BinaryOp::Mul: fn_name = "__oxide_checked_mul"; break;
                    case BinaryOp::Div: fn_name = "__oxide_checked_div"; break;
                    default: break;
                }
            }
            out_ << fn_name << "(";
            emit_expression(*bin->left);
            out_ << ", ";
            emit_expression(*bin->right);
            out_ << ")";
        } else if ((bin->op == BinaryOp::Equal || bin->op == BinaryOp::NotEqual) &&
                   bin->left->evaluated_type.kind == BaseTypeKind::Named) {
            out_ << "((";
            emit_expression(*bin->left);
            out_ << ").tag " << (bin->op == BinaryOp::Equal ? "== (" : "!= (");
            emit_expression(*bin->right);
            out_ << ").tag)";
        } else {
            out_ << "(";
            emit_expression(*bin->left);
            switch (bin->op) {
                case BinaryOp::Add: out_ << " + "; break;
                case BinaryOp::Sub: out_ << " - "; break;
                case BinaryOp::Mul: out_ << " * "; break;
                case BinaryOp::Div: out_ << " / "; break;
                case BinaryOp::Equal: out_ << " == "; break;
                case BinaryOp::NotEqual: out_ << " != "; break;
                case BinaryOp::Less: out_ << " < "; break;
                case BinaryOp::LessEqual: out_ << " <= "; break;
                case BinaryOp::Greater: out_ << " > "; break;
                case BinaryOp::GreaterEqual: out_ << " >= "; break;
            }
            emit_expression(*bin->right);
            out_ << ")";
        }
    } else if (auto* un = dynamic_cast<const UnaryExpr*>(&expr)) {
        if ((un->op == UnaryOp::Ref || un->op == UnaryOp::RefMut) && un->operand->evaluated_type.kind == BaseTypeKind::Array) {
            out_ << "(";
            emit_expression(*un->operand);
            out_ << ")";
            return;
        }
        switch (un->op) {
            case UnaryOp::Negate: out_ << "(-"; break;
            case UnaryOp::Not: out_ << "(!"; break;
            case UnaryOp::Ref:
            case UnaryOp::RefMut: out_ << "(&"; break;
            case UnaryOp::Deref: out_ << "(*"; break;
        }
        emit_expression(*un->operand);
        out_ << ")";
    } else if (auto* assign = dynamic_cast<const AssignExpr*>(&expr)) {
        emit_expression(*assign->target);
        out_ << " = ";
        emit_expression(*assign->value);
    } else if (auto* call = dynamic_cast<const CallExpr*>(&expr)) {
        if (call->callee == "println!") {
            if (call->arguments.empty()) {
                out_ << "printf(\"\\n\")";
                return;
            }
            if (auto* str_lit = dynamic_cast<const StringLiteralExpr*>(call->arguments[0].get())) {
                std::string fmt = str_lit->value;
                std::string c_fmt;
                size_t arg_idx = 1;
                for (size_t i = 0; i < fmt.size(); ++i) {
                    if (fmt[i] == '{' && i + 1 < fmt.size() && fmt[i + 1] == '}') {
                        if (arg_idx < call->arguments.size()) {
                            const auto& arg_t = call->arguments[arg_idx]->evaluated_type;
                            if (arg_t.kind == BaseTypeKind::Str) {
                                c_fmt += "%s";
                            } else if (arg_t.kind == BaseTypeKind::Bool) {
                                c_fmt += "%s";
                            } else if (arg_t.kind == BaseTypeKind::F32 || arg_t.kind == BaseTypeKind::F64) {
                                c_fmt += "%f";
                            } else {
                                c_fmt += "%d";
                            }
                            arg_idx++;
                        } else {
                            c_fmt += "{}";
                        }
                        i++; // skip '}'
                    } else {
                        c_fmt += fmt[i];
                    }
                }
                c_fmt += "\\n";
                out_ << "printf(\"" << c_fmt << "\"";
                for (size_t i = 1; i < call->arguments.size(); ++i) {
                    out_ << ", ";
                    if (call->arguments[i]->evaluated_type.kind == BaseTypeKind::Bool) {
                        out_ << "(";
                        emit_expression(*call->arguments[i]);
                        out_ << " ? \"true\" : \"false\")";
                    } else {
                        emit_expression(*call->arguments[i]);
                    }
                }
                out_ << ")";
                return;
            }
        }
        if (call->callee == "assert!") {
            out_ << "assert(";
            emit_expression(*call->arguments[0]);
            out_ << ")";
            return;
        }
        if (call->callee == "panic!") {
            out_ << "(fprintf(stderr, \"panicked: \"), ";
            if (!call->arguments.empty()) {
                emit_expression(*call->arguments[0]);
                out_ << ", ";
            }
            out_ << "fprintf(stderr, \"\\n\"), abort())";
            return;
        }
        if (call->callee == "sqrt") {
            if (aerospace_profile_) {
                if (call->evaluated_type.kind == BaseTypeKind::F32) {
                    out_ << "__oxide_checked_fsqrt_f32(";
                } else {
                    out_ << "__oxide_checked_fsqrt_f64(";
                }
            } else {
                if (call->evaluated_type.kind == BaseTypeKind::F32) {
                    out_ << "sqrtf(";
                } else {
                    out_ << "sqrt(";
                }
            }
            emit_expression(*call->arguments[0]);
            out_ << ")";
            return;
        }
        if (call->callee == "clamp") {
            if (aerospace_profile_) {
                if (call->evaluated_type.kind == BaseTypeKind::F32) {
                    out_ << "__oxide_checked_clamp_f32(";
                } else if (call->evaluated_type.kind == BaseTypeKind::F64) {
                    out_ << "__oxide_checked_clamp_f64(";
                } else {
                    out_ << "__oxide_checked_clamp_i32(";
                }
            } else {
                if (call->evaluated_type.kind == BaseTypeKind::F32) {
                    out_ << "__oxide_clamp_f32(";
                } else if (call->evaluated_type.kind == BaseTypeKind::F64) {
                    out_ << "__oxide_clamp_f64(";
                } else {
                    out_ << "__oxide_clamp_i32(";
                }
            }
            emit_expression(*call->arguments[0]);
            out_ << ", ";
            emit_expression(*call->arguments[1]);
            out_ << ", ";
            emit_expression(*call->arguments[2]);
            out_ << ")";
            return;
        }
        if (call->callee == "tmr_vote") {
            const char* voter = "__oxide_tmr_vote_i32";
            if (call->evaluated_type.kind == BaseTypeKind::F32) {
                voter = "__oxide_tmr_vote_f32";
            } else if (call->evaluated_type.kind == BaseTypeKind::F64) {
                voter = "__oxide_tmr_vote_f64";
            } else if (call->evaluated_type.kind == BaseTypeKind::Bool) {
                voter = "__oxide_tmr_vote_bool";
            }
            out_ << voter << "(";
            emit_expression(*call->arguments[0]);
            out_ << ", ";
            emit_expression(*call->arguments[1]);
            out_ << ", ";
            emit_expression(*call->arguments[2]);
            out_ << ", \"tmr_vote\")";
            return;
        }

        std::string callee = call->callee;
        size_t pos = 0;
        while ((pos = callee.find("::", pos)) != std::string::npos) {
            callee.replace(pos, 2, "__");
            pos += 2;
        }
        out_ << callee << "(";
        for (size_t i = 0; i < call->arguments.size(); ++i) {
            if (i > 0) out_ << ", ";
            emit_expression(*call->arguments[i]);
        }
        out_ << ")";
    } else if (auto* mc = dynamic_cast<const MethodCallExpr*>(&expr)) {
        if (mc->resolved_callee == "Option__is_some") {
            out_ << "((";
            emit_expression(*mc->receiver);
            out_ << ").tag == Option_Tag_Some)";
            return;
        }
        if (mc->resolved_callee == "Option__is_none") {
            out_ << "((";
            emit_expression(*mc->receiver);
            out_ << ").tag == Option_Tag_None)";
            return;
        }
        if (mc->resolved_callee == "Option__unwrap") {
            out_ << "((";
            emit_expression(*mc->receiver);
            out_ << ").tag == Option_Tag_Some ? (";
            emit_expression(*mc->receiver);
            out_ << ").data.Some : (fprintf(stderr, \"panicked at Option::unwrap() on None\\n\"), abort(), (";
            emit_expression(*mc->receiver);
            out_ << ").data.Some))";
            return;
        }
        if (mc->resolved_callee == "Result__is_ok") {
            out_ << "((";
            emit_expression(*mc->receiver);
            out_ << ").tag == Result_Tag_Ok)";
            return;
        }
        if (mc->resolved_callee == "Result__is_err") {
            out_ << "((";
            emit_expression(*mc->receiver);
            out_ << ").tag == Result_Tag_Err)";
            return;
        }
        if (mc->resolved_callee == "Result__unwrap") {
            out_ << "((";
            emit_expression(*mc->receiver);
            out_ << ").tag == Result_Tag_Ok ? (";
            emit_expression(*mc->receiver);
            out_ << ").data.Ok : (fprintf(stderr, \"panicked at Result::unwrap() on Err\\n\"), abort(), (";
            emit_expression(*mc->receiver);
            out_ << ").data.Ok))";
            return;
        }

        out_ << mc->resolved_callee << "(";
        if (mc->resolved_self_kind == SelfKind::Ref || mc->resolved_self_kind == SelfKind::RefMut) {
            if (mc->receiver->evaluated_type.is_ref) {
                emit_expression(*mc->receiver);
            } else {
                out_ << "&(";
                emit_expression(*mc->receiver);
                out_ << ")";
            }
        } else {
            emit_expression(*mc->receiver);
        }
        for (const auto& arg : mc->arguments) {
            out_ << ", ";
            emit_expression(*arg);
        }
        out_ << ")";
    } else if (auto* if_expr = dynamic_cast<const IfExpr*>(&expr)) {
        out_ << "(";
        emit_expression(*if_expr->condition);
        out_ << " ? ";
        if (if_expr->then_branch->trailing_expr) {
            emit_expression(*if_expr->then_branch->trailing_expr);
        } else {
            out_ << "0";
        }
        out_ << " : ";
        if (if_expr->else_branch && if_expr->else_branch->trailing_expr) {
            emit_expression(*if_expr->else_branch->trailing_expr);
        } else {
            out_ << "0";
        }
        out_ << ")";
    } else if (auto* ret = dynamic_cast<const ReturnExpr*>(&expr)) {
        out_ << "return";
        if (ret->value) {
            out_ << " ";
            emit_expression(*ret->value);
        }
    } else if (auto* s_init = dynamic_cast<const StructInitExpr*>(&expr)) {
        out_ << "((" << s_init->struct_name << "){ ";
        for (size_t i = 0; i < s_init->fields.size(); ++i) {
            if (i > 0) out_ << ", ";
            out_ << "." << s_init->fields[i].field_name << " = ";
            emit_expression(*s_init->fields[i].value);
        }
        out_ << " })";
    } else if (auto* fa = dynamic_cast<const FieldAccessExpr*>(&expr)) {
        out_ << "(";
        emit_expression(*fa->target);
        if (fa->target->evaluated_type.is_ref) {
            out_ << "->" << fa->field_name << ")";
        } else {
            out_ << "." << fa->field_name << ")";
        }
    } else if (auto* while_expr = dynamic_cast<const WhileExpr*>(&expr)) {
        if (dynamic_cast<const BinaryExpr*>(while_expr->condition.get())) {
            out_ << "while ";
            emit_expression(*while_expr->condition);
            out_ << " ";
        } else {
            out_ << "while (";
            emit_expression(*while_expr->condition);
            out_ << ") ";
        }
        emit_block(*while_expr->body, false);
    } else if (auto* ev = dynamic_cast<const EnumVariantExpr*>(&expr)) {
        out_ << ev->enum_name << "_" << ev->variant_name << "(";
        if (ev->payload) {
            emit_expression(*ev->payload);
        }
        out_ << ")";
    } else if (auto* match_expr = dynamic_cast<const MatchExpr*>(&expr)) {
        int mid = match_counter_++;
        std::string target_var = "_match_tgt_" + std::to_string(mid);
        std::string res_var = "_match_res_" + std::to_string(mid);
        bool has_res = (match_expr->evaluated_type.kind != BaseTypeKind::Unit);

        out_ << "({\n";
        indent_level_++;

        indent();
        out_ << map_type(match_expr->target->evaluated_type) << " " << target_var << " = ";
        emit_expression(*match_expr->target);
        out_ << ";\n";

        if (has_res) {
            indent();
            out_ << map_type(match_expr->evaluated_type) << " " << res_var << ";\n";
        }

        indent();
        out_ << "switch (" << target_var << ".tag) {\n";
        indent_level_++;

        for (const auto& arm : match_expr->arms) {
            indent();
            if (arm.pattern.kind == PatternKind::Wildcard) {
                out_ << "default: {\n";
            } else {
                out_ << "case " << arm.pattern.enum_name << "_Tag_" << arm.pattern.variant_name << ": {\n";
            }
            indent_level_++;

            if (arm.pattern.kind == PatternKind::Variant && !arm.pattern.binding_name.empty()) {
                std::string payload_type_str = "";
                for (const auto& e : program_.enums) {
                    if (e->name == arm.pattern.enum_name) {
                        for (const auto& v : e->variants) {
                            if (v.name == arm.pattern.variant_name && v.payload_type.has_value()) {
                                payload_type_str = map_type(*v.payload_type);
                                break;
                            }
                        }
                        break;
                    }
                }
                if (!payload_type_str.empty()) {
                    indent();
                    out_ << payload_type_str << " " << arm.pattern.binding_name
                         << " = " << target_var << ".data." << arm.pattern.variant_name << ";\n";
                }
            }

            emit_match_arm_body(*arm.body, res_var, has_res);
            indent();
            out_ << "break;\n";

            indent_level_--;
            indent();
            out_ << "}\n";
        }

        indent_level_--;
        indent();
        out_ << "}\n";

        if (has_res) {
            indent();
            out_ << res_var << ";\n";
        }

        indent_level_--;
        indent();
        out_ << "})";
    } else if (auto* str_lit = dynamic_cast<const StringLiteralExpr*>(&expr)) {
        out_ << "\"" << str_lit->value << "\"";
    } else if (auto* arr = dynamic_cast<const ArrayLiteralExpr*>(&expr)) {
        out_ << "{";
        for (size_t i = 0; i < arr->elements.size(); ++i) {
            if (i > 0) out_ << ", ";
            emit_expression(*arr->elements[i]);
        }
        out_ << "}";
    } else if (auto* rep = dynamic_cast<const ArrayRepeatExpr*>(&expr)) {
        out_ << "{";
        for (size_t i = 0; i < rep->count; ++i) {
            if (i > 0) out_ << ", ";
            emit_expression(*rep->value);
        }
        out_ << "}";
    } else if (auto* idx = dynamic_cast<const IndexExpr*>(&expr)) {
        if (aerospace_profile_ && idx->target->evaluated_type.kind == BaseTypeKind::Array && idx->target->evaluated_type.array_size > 0) {
            out_ << "(__OXIDE_BOUNDS_CHECK(";
            emit_expression(*idx->target);
            out_ << ", ";
            emit_expression(*idx->index);
            out_ << ", " << idx->target->evaluated_type.array_size << ")[";
            emit_expression(*idx->index);
            out_ << "])";
        } else {
            emit_expression(*idx->target);
            out_ << "[";
            emit_expression(*idx->index);
            out_ << "]";
        }
    } else if (auto* for_expr = dynamic_cast<const ForExpr*>(&expr)) {
        if (auto* range = dynamic_cast<const RangeExpr*>(for_expr->iterable.get())) {
            out_ << "for (int32_t " << for_expr->var_name << " = ";
            emit_expression(*range->start);
            out_ << "; " << for_expr->var_name << " < ";
            emit_expression(*range->end);
            out_ << "; ++" << for_expr->var_name << ") ";
            emit_block(*for_expr->body, false);
        }
    }
}

void CCodeGenerator::emit_match_arm_body(const Expression& body, const std::string& res_var, bool has_res) {
    if (auto* block = dynamic_cast<const BlockExpr*>(&body)) {
        for (const auto& stmt : block->statements) {
            emit_statement(*stmt);
        }
        if (block->trailing_expr) {
            indent();
            if (has_res) {
                out_ << res_var << " = ";
            }
            emit_expression(*block->trailing_expr);
            out_ << ";\n";
        }
    } else {
        indent();
        if (has_res) {
            out_ << res_var << " = ";
        }
        emit_expression(body);
        out_ << ";\n";
    }
}

